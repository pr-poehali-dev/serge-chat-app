export function generateBotReply(bot: BotInfo, userText: string): string {
  const lower = userText.trim().toLowerCase();

  if (GREETINGS.some((g) => lower.includes(g))) {
    return `Привет! Я ${bot.name} 👋 ${bot.description}`;
  }

  if (lower.includes("помощь") || lower.includes("help") || lower === "/start") {
    return `Я ${bot.name}. ${bot.description}\n\nПросто напишите мне, и я постараюсь помочь!`;
  }

  const pool = REPLIES_BY_CATEGORY[bot.category] || REPLIES_BY_CATEGORY["Другое"];
  return pool[Math.floor(Math.random() * pool.length)];
}
